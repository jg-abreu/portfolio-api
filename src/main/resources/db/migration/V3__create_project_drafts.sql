CREATE TABLE project_drafts (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 0,
    slug varchar(100) NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    repository_url varchar(300) NOT NULL,
    live_url varchar(500) NOT NULL,
    stack varchar(1000) NOT NULL,
    display_order integer NOT NULL CHECK (display_order >= 0),
    status varchar(16) NOT NULL CHECK (status IN ('DRAFT', 'ARCHIVED')),
    en_title varchar(150) NOT NULL CHECK (length(trim(en_title)) > 0),
    en_tagline varchar(300) NOT NULL,
    en_problem text NOT NULL,
    en_decisions text NOT NULL,
    en_result text NOT NULL,
    en_body text NOT NULL,
    pt_title varchar(150) NOT NULL CHECK (length(trim(pt_title)) > 0),
    pt_tagline varchar(300) NOT NULL,
    pt_problem text NOT NULL,
    pt_decisions text NOT NULL,
    pt_result text NOT NULL,
    pt_body text NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);