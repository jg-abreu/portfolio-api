CREATE TABLE recommendation_sections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('BOOKS', 'ITEMS')),
    en_title VARCHAR(80) NOT NULL CHECK (length(trim(en_title)) > 0),
    pt_title VARCHAR(80) NOT NULL CHECK (length(trim(pt_title)) > 0),
    display_order INT NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

DELETE FROM recommendation_publications;
DELETE FROM recommendation_drafts;

ALTER TABLE recommendation_drafts
    ADD COLUMN section_id BIGINT NOT NULL REFERENCES recommendation_sections(id),
    ADD COLUMN display_order INT NOT NULL DEFAULT 0 CHECK (display_order >= 0);

CREATE INDEX recommendation_drafts_section ON recommendation_drafts(section_id, display_order);
