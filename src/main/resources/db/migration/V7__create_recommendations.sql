CREATE TABLE recommendation_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    slug VARCHAR(100) NOT NULL UNIQUE,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'ARCHIVED')),
    payload TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE recommendation_publications (
    recommendation_id BIGINT PRIMARY KEY REFERENCES recommendation_drafts(id) ON DELETE CASCADE,
    slug VARCHAR(100) NOT NULL UNIQUE,
    revision UUID NOT NULL UNIQUE,
    draft_version BIGINT NOT NULL CHECK (draft_version >= 0),
    image_key VARCHAR(68) NOT NULL,
    payload TEXT NOT NULL
);
CREATE INDEX recommendation_publications_image ON recommendation_publications(image_key);
